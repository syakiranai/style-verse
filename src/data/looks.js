export function getVisibleNavItems(role, isAuthenticated) {
  return NAV_ITEMS.filter((item) => {
    if (item.roles && !item.roles.includes(role)) return false;
    return true;
  }).map((item) => {
    if (item.id === 'login') {
      if (!isAuthenticated) return { ...item, label: 'Login' };
      return {
        ...item,
        label: role === 'admin' ? 'Admin Akun' : role === 'operator' ? 'Operator Akun' : 'User',
      };
    }
    return item;
  });
}

